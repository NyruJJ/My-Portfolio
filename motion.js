/* Portfolio 2.0 — progressive reveal and stagger for static + filtered content. */
(() => {
  'use strict';
  const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)');
  if (reducedMotion.matches) return;

  document.documentElement.classList.add('motion-ready');

  const targets = [
    '.metrics .metric',
    '#expertise .section-kicker',
    '#expertise .expertise-intro',
    '#expertise .expertise-network-panel',
    '#expertise .expertise-card',
    '#work .section-kicker',
    '#work .section-header',
    '#work .filter-bar',
    '#experience .section-kicker',
    '#experience .section-header',
    '#experience .timeline-item',
    '#education .section-kicker',
    '#education .section-header',
    '#education .education-grid > *',
    '#contact .section-kicker',
    '#contact .cta-inner',
    '.footer .footer-inner'
  ];

  const observer = 'IntersectionObserver' in window ? new IntersectionObserver(entries => {
    for (const entry of entries) {
      if (!entry.isIntersecting) continue;
      entry.target.classList.add('is-visible');
      observer.unobserve(entry.target);
    }
  }, { rootMargin: '0px 0px -35px 0px', threshold: 0.08 }) : null;

  function register(el, i = 0, direction = '') {
    if (!el || el.dataset.motionBound === 'true') return;
    el.dataset.motionBound = 'true';
    el.classList.add('motion-reveal');
    if (direction) el.classList.add(direction);
    el.style.setProperty('--motion-delay', `${Math.min(i % 4, 3) * 95}ms`);
    if (observer) observer.observe(el);
    else el.classList.add('is-visible');
  }

  for (const selector of targets) {
    document.querySelectorAll(selector).forEach((el, i) => {
      register(el, i, selector.includes('network-panel') ? 'motion-from-right' : '');
    });
  }

  // Project cards are generated and regenerated by the site's filters/search.
  const projectGrid = document.getElementById('projects-grid');
  if (projectGrid) {
    function registerCards() {
      projectGrid.querySelectorAll('.project-card').forEach((el, i) => register(el, i));
    }
    registerCards();
    const watcher = new MutationObserver(registerCards);
    watcher.observe(projectGrid, { childList: true, subtree: false });
  }

  // Ensure controls don't appear inert if users change their motion preference mid-session.
  reducedMotion.addEventListener?.('change', event => {
    if (!event.matches) return;
    observer?.disconnect();
    document.querySelectorAll('.motion-reveal').forEach(el => el.classList.add('is-visible'));
    document.documentElement.classList.remove('motion-ready');
  });
})();
